#!/bin/sh
# lab-izleri.sh: list files in system directories that no apk package owns, i.e. hand
# copies and lab leftovers, so a release image can be checked for them (7 Kasım).
# Run on the phone: doas sh lab-izleri.sh   (read-only, writes only /tmp/lab-izleri.*)
# Known items (2026-11-07 inventory):
#   razer-nicole-lab package       /etc/doas.d/razer-lab.conf (passwordless doas) - a
#                                  package, so not listed here; dropped by pmos-hazirla --yayin
#   /var/lib/uyku-test, pil-olcum  sleep/battery measurement scripts and data
#   /etc/systemd/system/sessiz-*.service
#                                  sleep experiments, only run if a flag file exists
#   /etc/kernel-cmdline.d/60-ufs-yazma.conf
#                                  UFS write guard ranges (safety, not lab: keep; should be
#                                  generated by the installer for v0.1)
#   /lib/firmware/qcom/sm8350/razer/nicole, ath11k/WCN6855/hw1.1, /usr/share/qcom
#                                  Razer firmware: from nicole-firmware-cek, never packaged
T=/tmp/lab-izleri
apk info -L $(apk info 2>/dev/null) 2>/dev/null | grep -v "contains:$" | grep -v '^$' | sed 's|^|/|' > $T.s1
# usr-merge: packages may list /bin, /sbin, /lib paths that live under /usr
sed -e 's|^/bin/|/usr/bin/|' -e 's|^/sbin/|/usr/sbin/|' -e 's|^/lib/|/usr/lib/|' -e 's|^/usr/sbin/|/usr/bin/|' $T.s1 > $T.s2
cat $T.s1 $T.s2 | sort -u > $T.sahipli
find /etc /usr /var/lib /boot /opt -xdev \( -type f -o -type l \) 2>/dev/null \
 | sed -e 's|^/usr/sbin/|/usr/bin/|' \
 | grep -vE '^/usr/lib/modules/|/__pycache__/|^/var/lib/(apk|systemd|NetworkManager|bluetooth|dbus|polkit-1|alsa|upower|misc|private|iio-sensor-proxy|swclock-offset|nicole-saat|lastlog|machines|portables)|^/etc/(ssh/ssh_host_|machine-id|hostname|shadow|passwd|group|gshadow|resolv.conf|localtime|NetworkManager/system-connections/|apk/|ld.so.cache|subuid|subgid|\.pwd\.lock|adjtime|mtab)|^/usr/share/(mime/|fonts/)|icon-theme.cache|gschemas.compiled|mimeinfo.cache|hwdb.bin|^/usr/lib/locale' \
 | sort -u > $T.hepsi
comm -23 $T.hepsi $T.sahipli | grep -vE "\.(wants|requires)/" | while read f; do l=$(readlink -f "$f"); case "$l" in */busybox) ;; *) echo "$f";; esac; done
rm -f $T.s1 $T.s2 $T.sahipli $T.hepsi
